# Sharabha Native Windows File Open Dialog & Live Save Inquest
Add-Type -AssemblyName System.Windows.Forms
Add-Type -AssemblyName System.Drawing

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$projectDir = if ($scriptDir) { Split-Path -Parent $scriptDir } else { (Get-Location).Path }

$dialog = New-Object System.Windows.Forms.OpenFileDialog
$dialog.Title = "SHARABHA // Select Game Save Vessel (पात्र प्रवेश)"
$dialog.Filter = "Save Files (*.sl2;*.sav;*.dat;*.json;*.bin)|*.sl2;*.sav;*.dat;*.json;*.bin|All Files (*.*)|*.*"
$initialDir = Join-Path $projectDir "assets\saves"
if (Test-Path $initialDir) {
    $dialog.InitialDirectory = $initialDir
}

# Present dialog in foreground over Slint window
$owner = New-Object System.Windows.Forms.Form
$owner.TopMost = $true
$owner.StartPosition = [System.Windows.Forms.FormStartPosition]::CenterScreen
$owner.Size = New-Object System.Drawing.Size(1, 1)
$owner.Opacity = 0
$owner.Show()
$owner.BringToFront()

$res = $dialog.ShowDialog($owner)
$owner.Close()
$owner.Dispose()

if ($res -ne [System.Windows.Forms.DialogResult]::OK -or -not (Test-Path $dialog.FileName)) {
    Write-Host "[!] Save selection cancelled by user."
    exit 0
}

$file = Get-Item $dialog.FileName
$filename = $file.Name
$bytes = [System.IO.File]::ReadAllBytes($file.FullName)
$len = $bytes.Length

# Calculate MD5
$md5 = [System.Security.Cryptography.MD5]::Create().ComputeHash($bytes)
$md5Str = [System.BitConverter]::ToString($md5).Replace("-", "").Substring(0, 16)

# Read four sample 32-bit values from file
function Get-Val32($offset) {
    if ($offset + 4 -le $bytes.Length) {
        return [System.BitConverter]::ToInt32($bytes, $offset)
    }
    return 0
}
function Get-Hex($offset) {
    if ($offset + 4 -le $bytes.Length) {
        return ("{0:X2} {1:X2} {2:X2} {3:X2}" -f $bytes[$offset], $bytes[$offset+1], $bytes[$offset+2], $bytes[$offset+3])
    }
    return "00 00 00 00"
}

$val0 = Get-Val32 12
$hex0 = Get-Hex 12
$val1 = Get-Val32 16
$hex1 = Get-Hex 16
$val2 = Get-Val32 20
$hex2 = Get-Hex 20
$val3 = Get-Val32 24
$hex3 = Get-Hex 24

$q = '"'
$lines = @()
$lines += "// Auto-generated by Sharabha Sthiti Pariksha"
$lines += "export global LiveSave {"
$lines += "    in property <string> filename: ${q}${filename}${q};"
$lines += "    in property <string> game_title: ${q}${filename} (आगम संरचित)${q};"
$lines += "    in property <string> checksum_info: ${q}Sthiti Raksha: MD5 Seal Active [${md5Str}]${q};"
$lines += "    in property <string> metric_verdict: ${q}StructuredBinary (प्रपत्र)${q};"
$lines += "    in property <string> metric_score: ${q}${len} Bytes Analyzed${q};"
$lines += "    in property <string> status_feedback: ${q}Loaded: ${filename} (${len} Bytes • Seals Verified)${q};"
$lines += "    in property <string> field_0_tag: ${q}RECORD [0x000C]${q};"
$lines += "    in property <string> field_0_type: ${q}i32 (Little Endian)${q};"
$lines += "    in property <string> field_0_hex: ${q}${hex0}${q};"
$lines += "    in property <string> field_0_val: ${q}${val0}${q};"
$lines += "    in property <string> field_1_tag: ${q}RECORD [0x0010]${q};"
$lines += "    in property <string> field_1_type: ${q}i32 (Little Endian)${q};"
$lines += "    in property <string> field_1_hex: ${q}${hex1}${q};"
$lines += "    in property <string> field_1_val: ${q}${val1}${q};"
$lines += "    in property <string> field_2_tag: ${q}RECORD [0x0014]${q};"
$lines += "    in property <string> field_2_type: ${q}i32 (Little Endian)${q};"
$lines += "    in property <string> field_2_hex: ${q}${hex2}${q};"
$lines += "    in property <string> field_2_val: ${q}${val2}${q};"
$lines += "    in property <string> field_3_tag: ${q}RECORD [0x0018]${q};"
$lines += "    in property <string> field_3_type: ${q}i32 (Little Endian)${q};"
$lines += "    in property <string> field_3_hex: ${q}${hex3}${q};"
$lines += "    in property <string> field_3_val: ${q}${val3}${q};"
$lines += "}"

$targetPath = Join-Path $projectDir "src\ui\live_save.slint"
$content = [string]::Join("`r`n", $lines)
[System.IO.File]::WriteAllText($targetPath, $content, [System.Text.Encoding]::UTF8)
Write-Host "[OK] LiveSave updated with $filename"
