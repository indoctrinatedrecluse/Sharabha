param(
    [string]$WorkingDir = ""
)

$baseDir = if ($WorkingDir -and (Test-Path $WorkingDir)) {
    (Resolve-Path $WorkingDir).Path
} else {
    $scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
    if ($scriptDir) { Split-Path -Parent $scriptDir } else { (Get-Location).Path }
}

$defaultInstallPath = "$env:LOCALAPPDATA\Programs\Sharabha"
$detectedPath = $defaultInstallPath
$isInstalled = $false
$installedVersion = ""

# 1. Check Windows Uninstall Registry for Existing Sharabha Registration
$regKey = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\Sharabha"
if (Test-Path $regKey) {
    try {
        $props = Get-ItemProperty $regKey -ErrorAction SilentlyContinue
        if ($props) {
            if ($props.InstallLocation -and (Test-Path $props.InstallLocation)) {
                $detectedPath = $props.InstallLocation
                $isInstalled = $true
            }
            if ($props.DisplayVersion) {
                $installedVersion = $props.DisplayVersion
            }
        }
    } catch { }
}

# 2. Check if Sharabha.exe exists in detected location or default install folder
if (-not $isInstalled) {
    if (Test-Path (Join-Path $defaultInstallPath "bin\Sharabha.exe")) {
        $detectedPath = $defaultInstallPath
        $isInstalled = $true
        $installedVersion = "0.1.0"
    } elseif (Test-Path "C:\Software\Sharabha\bin\Sharabha.exe") {
        $detectedPath = "C:\Software\Sharabha"
        $isInstalled = $true
        $installedVersion = "0.1.0"
    }
}

# 3. Format path for Slint string literal (escaped backslashes)
$escapedPath = $detectedPath.Replace("\", "\\").Replace('"', '\"')
$stateFile = Join-Path $baseDir "src\ui\installer_state.slint"

$lines = @(
    "// Sharabha Installer Dynamic State Configuration",
    "// Automatically generated by installer_check.ps1",
    "export global InstallerState {",
    "    in property <bool> is_already_installed: $($isInstalled.ToString().ToLower());",
    "    in property <string> installed_version: `"$installedVersion`";",
    "    in property <string> detected_install_path: `"$escapedPath`";",
    "}"
)

$content = [string]::Join("`r`n", $lines)
[System.IO.File]::WriteAllText($stateFile, $content, [System.Text.Encoding]::UTF8)

Write-Host "[OK] Installer State Updated: is_already_installed=$isInstalled, path=$detectedPath"
