# Sharabha Real Windows Process Enumerator
# Queries active OS tasks and generates src/ui/live_processes.slint

param(
    [string]$OutPath = "src\ui\live_processes.slint"
)

$allProcs = Get-Process -ErrorAction SilentlyContinue | Where-Object { $_.Id -gt 4 } | Sort-Object -Descending { [bool]$_.MainWindowTitle }, WorkingSet64

$items = @()
$seen = @{}
foreach ($p in $allProcs) {
    if ($seen[$p.ProcessName]) { continue }
    $seen[$p.ProcessName] = $true
    $items += $p
    if ($items.Count -ge 12) { break }
}

if ($items.Count -lt 12) {
    foreach ($p in $allProcs) {
        $items += $p
        if ($items.Count -ge 12) { break }
    }
}

$lines = @()
$lines += "// Auto-generated by Sharabha Win32 Netra Inquest"
$lines += "// Real Windows Processes running on host"
$lines += "export global LiveProcesses {"

for ($i = 0; $i -lt 12; $i++) {
    if ($i -lt $items.Count) {
        $p = $items[$i]
        $name = $p.ProcessName + ".exe"
        $pidVal = $p.Id
        $t = $p.MainWindowTitle
        if (-not $t) { $t = $p.ProcessName + " [Background Host]" }
        $t = $t.Replace('"', "'")
        if ($t.Length -gt 45) { $t = $t.Substring(0, 42) + "..." }
        $ramMb = [Math]::Round($p.WorkingSet64 / 1MB)
        $ramStr = "$ramMb MB"
        $arch = if ([System.Environment]::Is64BitOperatingSystem) { "x64 Native" } else { "x86 Native" }
    } else {
        $name = "idle.exe"
        $pidVal = 0
        $t = "System Idle"
        $ramStr = "0 MB"
        $arch = "x64 Native"
    }

    $q = '"'
    $lines += "    in property <string> proc_${i}_name: $q$name$q;"
    $lines += "    in property <int> proc_${i}_pid: $pidVal;"
    $lines += "    in property <string> proc_${i}_title: $q$t$q;"
    $lines += "    in property <string> proc_${i}_ram: $q$ramStr$q;"
    $lines += "    in property <string> proc_${i}_arch: $q$arch$q;"
}

$lines += "}"

$content = [string]::Join("`r`n", $lines)
[System.IO.File]::WriteAllText($OutPath, $content, [System.Text.Encoding]::UTF8)
Write-Output "LiveProcesses generated at $OutPath"
