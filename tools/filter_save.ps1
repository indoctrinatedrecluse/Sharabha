param(
    [string]$Query = ""
)

# SHARABHA // DYNAMIC & GATED SAVE KEY-VALUE FILTER ENGINE (अन्वेषण शोधन)
# Filters extracted key-values by key, offset, type, value, or confidence rating.
# Supports instantaneous reload into LiveSave and auto-reload into Slint.

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$projectDir = if ($scriptDir) { Split-Path -Parent $scriptDir } else { (Get-Location).Path }
$cachePath = Join-Path $projectDir "assets\saves\current_save_cache.json"

if (-not (Test-Path $cachePath)) {
    # If cache doesn't exist yet, reparse active save first
    & (Join-Path $scriptDir "open_dialog.ps1") -Reparse
    if (-not (Test-Path $cachePath)) { exit 0 }
}

try {
    $raw = [System.IO.File]::ReadAllText($cachePath)
    $cache = $raw | ConvertFrom-Json
} catch {
    Write-Warning "Failed to read save cache: $_"
    exit 1
}

$trimmedQuery = if ($Query) { $Query.Trim() } else { "" }
$allRows = $cache.rows

if ($trimmedQuery -eq "") {
    $filtered = $allRows
} else {
    $filtered = @($allRows | Where-Object {
        ($_.key -and $_.key.IndexOf($trimmedQuery, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) -or
        ($_.offset -and $_.offset.IndexOf($trimmedQuery, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) -or
        ($_.type -and $_.type.IndexOf($trimmedQuery, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) -or
        ($_.val -and ([string]$_.val).IndexOf($trimmedQuery, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) -or
        ($_.conf -and $_.conf.IndexOf($trimmedQuery, [System.StringComparison]::OrdinalIgnoreCase) -ge 0)
    })
}

$filteredCount = if ($filtered) { $filtered.Count } else { 0 }
$totalExtracted = if ($cache.totalExtracted) { $cache.totalExtracted } else { if ($allRows) { $allRows.Count } else { 0 } }
$isDeterministic = if ($null -ne $cache.isDeterministicProfile) { $cache.isDeterministicProfile.ToString().ToLower() } else { "true" }

# Helper for Slint string escaping
function Escape-Slint($str) {
    if (-not $str) { return "" }
    return ([string]$str).Replace('\', '\\').Replace('"', '\"')
}

$q = '"'
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("// Auto-generated by Sharabha Sthiti Pariksha Engine (Filtered)")
$lines.Add("export struct SaveKeyValueRowData {")
$lines.Add("    offset: string,")
$lines.Add("    key: string,")
$lines.Add("    type_name: string,")
$lines.Add("    conf: string,")
$lines.Add("    hex: string,")
$lines.Add("    val: string,")
$lines.Add("}")
$lines.Add("")
$lines.Add("export global LiveSave {")
$lines.Add("    in property <int> active_tab_hint: 1;")
$lines.Add("    in property <bool> skip_splash_hint: true;")
$lines.Add("    in property <bool> is_deterministic_profile: $isDeterministic;")
$lines.Add("    in property <string> filename: ${q}$(Escape-Slint $cache.filename)${q};")
$lines.Add("    in property <string> game_title: ${q}$(Escape-Slint $cache.gameTitle)${q};")
$lines.Add("    in property <string> checksum_info: ${q}Sthiti Raksha: MD5 Seal Active [$(Escape-Slint $cache.md5Str)]${q};")
$lines.Add("    in property <string> metric_verdict: ${q}$(Escape-Slint $cache.verdict)${q};")
$lines.Add("    in property <string> metric_score: ${q}$($cache.len) Bytes Analyzed${q};")
$feedback = if ($trimmedQuery -eq "") {
    "Loaded: $(Escape-Slint $cache.filename) ($totalExtracted Key-Values, All Shown)"
} else {
    "Filter '$trimmedQuery': Showing $filteredCount of $totalExtracted key-values"
}
$lines.Add("    in property <string> status_feedback: ${q}${feedback}${q};")
$lines.Add("    in property <int> total_extracted_count: ${totalExtracted};")
$lines.Add("    in property <string> search_filter: ${q}$(Escape-Slint $trimmedQuery)${q};")
$lines.Add("    in property <int> filtered_count: ${filteredCount};")
$lines.Add("")
$lines.Add("    in property <[SaveKeyValueRowData]> rows: [")

for ($i = 0; $i -lt $filteredCount; $i++) {
    $r = $filtered[$i]
    $o = Escape-Slint $r.offset
    $k = Escape-Slint $r.key
    $t = Escape-Slint $r.type
    $c = Escape-Slint $r.conf
    $h = Escape-Slint $r.hex
    $v = Escape-Slint $r.val
    $comma = if ($i -lt $filteredCount - 1) { "," } else { "" }
    $lines.Add("        { offset: ${q}${o}${q}, key: ${q}${k}${q}, type_name: ${q}${t}${q}, conf: ${q}${c}${q}, hex: ${q}${h}${q}, val: ${q}${v}${q} }${comma}")
}
$lines.Add("    ];")
$lines.Add("")

# Scalar legacy row properties
for ($i = 0; $i -lt 10; $i++) {
    $o = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].offset } else { "" }
    $k = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].key } else { "" }
    $t = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].type } else { "" }
    $c = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].conf } else { "" }
    $h = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].hex } else { "" }
    $v = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].val } else { "" }
    $lines.Add("    in property <string> row_${i}_offset: ${q}${o}${q};")
    $lines.Add("    in property <string> row_${i}_key: ${q}${k}${q};")
    $lines.Add("    in property <string> row_${i}_type: ${q}${t}${q};")
    $lines.Add("    in property <string> row_${i}_conf: ${q}${c}${q};")
    $lines.Add("    in property <string> row_${i}_hex: ${q}${h}${q};")
    $lines.Add("    in property <string> row_${i}_val: ${q}${v}${q};")
}

# Legacy field aliases
for ($i = 0; $i -lt 4; $i++) {
    $k = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].key } else { "" }
    $t = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].type } else { "" }
    $h = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].hex } else { "" }
    $v = if ($i -lt $filteredCount) { Escape-Slint $filtered[$i].val } else { "" }
    $lines.Add("    in property <string> field_${i}_tag: ${q}${k}${q};")
    $lines.Add("    in property <string> field_${i}_type: ${q}${t}${q};")
    $lines.Add("    in property <string> field_${i}_hex: ${q}${h}${q};")
    $lines.Add("    in property <string> field_${i}_val: ${q}${v}${q};")
}

$lines.Add("}")

$targetPath = Join-Path $projectDir "src\ui\live_save.slint"
$content = [string]::Join("`r`n", $lines)
[System.IO.File]::WriteAllText($targetPath, $content, (New-Object System.Text.UTF8Encoding $true))
Write-Host "[OK] LiveSave filtered ($filteredCount of $totalExtracted rows matching '$trimmedQuery')"

# Touch src\ui\app.slint to trigger auto-reload in slint-viewer
$appSlint = Join-Path $projectDir "src\ui\app.slint"
if (Test-Path $appSlint) {
    (Get-Item $appSlint).LastWriteTime = Get-Date
}
